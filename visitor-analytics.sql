-- YouTube Mastery Academy: privacy-conscious website visitor analytics
-- Run once in Supabase SQL Editor. A separate table is used so the existing
-- visitor_events table and its policies are not changed.

create table if not exists public.site_visitor_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  user_id uuid null,
  page_path varchar(300) not null,
  page_title varchar(200) null,
  referrer varchar(500) null,
  device_type text not null check (device_type in ('mobile','tablet','desktop')),
  event_type text not null check (event_type in ('page_view','heartbeat')),
  created_at timestamptz not null default now()
);

create index if not exists site_visitor_events_created_at_idx on public.site_visitor_events (created_at desc);
create index if not exists site_visitor_events_visitor_created_idx on public.site_visitor_events (visitor_id, created_at desc);
create index if not exists site_visitor_events_page_created_idx on public.site_visitor_events (page_path, created_at desc);

alter table public.site_visitor_events enable row level security;

drop policy if exists "Allow website visitor event recording" on public.site_visitor_events;
create policy "Allow website visitor event recording"
on public.site_visitor_events for insert to anon, authenticated
with check (
  length(visitor_id) between 1 and 80
  and length(page_path) between 1 and 300
  and (page_title is null or length(page_title) <= 200)
  and (referrer is null or length(referrer) <= 500)
  and device_type in ('mobile','tablet','desktop')
  and event_type in ('page_view','heartbeat')
  and (user_id is null or user_id = auth.uid())
);

drop policy if exists "Admins read website visitor analytics" on public.site_visitor_events;
create policy "Admins read website visitor analytics"
on public.site_visitor_events for select to authenticated
using (public.is_admin());

grant insert on public.site_visitor_events to anon, authenticated;
grant select on public.site_visitor_events to authenticated;
grant usage, select on sequence public.site_visitor_events_id_seq to anon, authenticated;

create or replace function public.get_website_visitor_analytics()
returns jsonb language plpgsql stable security definer
set search_path = public, pg_temp
as $$
declare result jsonb;
begin
  if not coalesce(public.is_admin(), false) then raise exception 'Admin access required'; end if;
  select jsonb_build_object(
    'total_page_views', (select count(*) from public.site_visitor_events where event_type='page_view'),
    'unique_visitors_30d', (select count(distinct visitor_id) from public.site_visitor_events where event_type='page_view' and created_at >= now()-interval '30 days'),
    'active_visitors_5m', (select count(distinct visitor_id) from public.site_visitor_events where created_at >= now()-interval '5 minutes'),
    'student_page_views_30d', (select count(*) from public.site_visitor_events where event_type='page_view' and user_id is not null and created_at >= now()-interval '30 days'),
    'top_pages', (select coalesce(jsonb_agg(to_jsonb(p)), '[]'::jsonb) from (select page_path,count(*)::bigint as views from public.site_visitor_events where event_type='page_view' and created_at >= now()-interval '30 days' group by page_path order by views desc limit 8) p),
    'recent_visits', (select coalesce(jsonb_agg(to_jsonb(v)), '[]'::jsonb) from (select visitor_id,user_id,page_path,page_title,device_type,event_type,created_at from public.site_visitor_events order by created_at desc limit 30) v)
  ) into result;
  return result;
end;
$$;

revoke all on function public.get_website_visitor_analytics() from public;
grant execute on function public.get_website_visitor_analytics() to authenticated;
